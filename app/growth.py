"""Growth page: the career as numbers, built from knowledge/timeline.csv and projects.csv."""
from __future__ import annotations

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

from app.common import TYPE_COLORS, projects, subject, timeline
from aboutme.timeline import compute_kpis, seniority_steps, toolset_growth

name = subject()
career = timeline()
repos = projects()
kpis = compute_kpis(career, repos)
LEVELS = {1: "Intern", 2: "Specialist / consultant", 3: "Engineer", 4: "Senior"}

st.title(f"{name}'s growth in numbers")
st.caption("Built from the structured timeline she maintains, not generated by the AI.")

cols = st.columns(6)
cols[0].metric("Years active", f"{kpis.years_since_first_role:g}", border=True)
cols[1].metric("Organisations", kpis.organisations, border=True)
cols[2].metric("Countries", kpis.countries, border=True)
cols[3].metric("Degrees", kpis.degrees, border=True)
cols[4].metric("Tools & methods", kpis.tools, border=True)
cols[5].metric("Side projects", kpis.side_projects, border=True)
st.markdown(f"**Now:** {kpis.current_title}")

# --- Timeline ---------------------------------------------------------------
st.subheader("Timeline")
label = lambda r: f"{r['org']}: {r['title']}" + (" *" if r["needs_confirmation"] else "")  # noqa: E731
bars = career[career["start_date"].notna()].copy()
bars["label"] = bars.apply(label, axis=1)
order = career.apply(label, axis=1).tolist()
fig = px.timeline(
    bars, x_start="start_date", x_end="end_date", y="label", color="type",
    color_discrete_map=TYPE_COLORS, hover_data={"period": True, "where": True, "label": False, "type": False},
    category_orders={"label": order},
)
for i, (_, row) in enumerate(career[career["start_date"].isna()].iterrows()):
    fig.add_trace(go.Scatter(
        x=[row["end_date"]], y=[label(row)], mode="markers", name=f"{row['type']} (completed)",
        showlegend=i == 0,
        marker={"symbol": "diamond", "size": 14, "color": TYPE_COLORS[row["type"]]},
        hovertemplate=f"{row['title']}<br>{row['period']}<extra></extra>",
    ))
fig.update_yaxes(categoryorder="array", categoryarray=order[::-1], title=None)
fig.update_xaxes(title=None)
fig.update_layout(height=360, margin={"l": 0, "r": 0, "t": 10, "b": 0}, legend_title_text="")
st.plotly_chart(fig, width="stretch")
st.caption("◆ marks a degree's completion date (start dates aren't on the resume). * needs confirmation.")

left, right = st.columns(2)

def label_positions(n: int) -> list[str]:
    """Alternate labels above/below so neighbouring roles at the same level don't overlap."""
    pos = ["top center" if i % 2 == 0 else "bottom center" for i in range(n)]
    if n:
        pos[0] = pos[0].replace("center", "right")
        pos[-1] = pos[-1].replace("center", "left")
    return pos


# --- Seniority ---------------------------------------------------------------
with left:
    st.subheader("Seniority")
    steps = seniority_steps(career)
    sen = go.Figure(go.Scatter(
        x=steps["start_date"], y=steps["level_num"], mode="lines+markers+text", line_shape="hv",
        text=steps["org"], textposition=label_positions(len(steps)), cliponaxis=False, line={"color": TYPE_COLORS["work"], "width": 3},
        marker={"size": 9}, hovertemplate="%{text}<br>%{x|%b %Y}<extra></extra>",
    ))
    sen.update_yaxes(tickvals=list(LEVELS), ticktext=list(LEVELS.values()), range=[0.5, 4.7], title=None)
    sen.update_layout(height=320, margin={"l": 0, "r": 20, "t": 20, "b": 0})
    st.plotly_chart(sen, width="stretch")

# --- Toolset ---------------------------------------------------------------
with right:
    st.subheader("Toolset growth")
    tools = toolset_growth(career)
    tg = go.Figure()
    tg.add_trace(go.Bar(x=tools["date"], y=tools["new_count"], name="New at this step",
                        marker_color="#9DB7EC", customdata=tools[["label", "new_tools"]],
                        hovertemplate="%{customdata[0]}<br>New: %{customdata[1]}<extra></extra>"))
    tg.add_trace(go.Scatter(x=tools["date"], y=tools["cumulative"], name="Cumulative",
                            mode="lines+markers", line={"color": TYPE_COLORS["work"], "width": 3}))
    tg.update_layout(height=320, margin={"l": 0, "r": 0, "t": 10, "b": 0},
                     legend={"orientation": "h", "y": -0.15}, yaxis_title=None)
    st.plotly_chart(tg, width="stretch")

# --- Results ---------------------------------------------------------------
st.subheader("Measurable results")
results = career[(career["type"] == "work") & (career["key_metric"] != "")]
st.dataframe(
    results[["org", "title", "period", "key_metric"]].rename(
        columns={"org": "Organisation", "title": "Role", "period": "Period", "key_metric": "Result"}),
    hide_index=True, width="stretch",
)

# --- Projects ---------------------------------------------------------------
st.subheader("Side projects")
pc1, pc2 = st.columns([1, 2])
with pc1:
    by_cat = repos["category"].value_counts().rename_axis("Category").reset_index(name="Projects")
    cat = px.bar(by_cat, x="Projects", y="Category", orientation="h", color_discrete_sequence=[TYPE_COLORS["work"]])
    cat.update_layout(height=320, margin={"l": 0, "r": 0, "t": 10, "b": 0}, yaxis={"categoryorder": "total ascending", "title": None})
    st.plotly_chart(cat, width="stretch")
with pc2:
    st.dataframe(
        repos[["name", "category", "year", "stack", "url"]].rename(columns=str.title),
        hide_index=True, width="stretch", height=320,
        column_config={"Url": st.column_config.LinkColumn("Repository", display_text="Open")},
    )

flagged = career[career["needs_confirmation"]]
if len(flagged):
    with st.expander(f"{len(flagged)} timeline entries still need confirmation"):
        for _, row in flagged.iterrows():
            st.markdown(f"- **{row['org']}, {row['title']}**: {row['status'].split(':', 1)[-1].strip()}")
